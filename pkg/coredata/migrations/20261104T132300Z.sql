        RAISE EXCEPTION 'private suffix under co.uk mismatch: %', cmp_registrable_domain('foo.dh.bytemark.co.uk');
    END IF;
    IF cmp_registrable_domain('www.ck') IS DISTINCT FROM 'www.ck'
        OR cmp_registrable_domain('www.www.ck') IS DISTINCT FROM 'www.ck'
        OR cmp_registrable_domain('a.b.test.ck') IS DISTINCT FROM 'b.test.ck' THEN
        RAISE EXCEPTION 'ck registrable domain mismatch';
    END IF;
    IF cmp_registrable_domain('localhost') IS DISTINCT FROM 'localhost'
        OR cmp_registrable_domain('127.0.0.1') IS DISTINCT FROM '127.0.0.1' THEN
        RAISE EXCEPTION 'local host mismatch';
    END IF;
    IF cmp_banner_registrable_domain('https://www.shop.example.com') IS DISTINCT FROM 'example.com'
        OR cmp_banner_registrable_domain('https://localhost:3000') IS DISTINCT FROM 'localhost'
        OR cmp_banner_registrable_domain('https://foo.vercel.app') IS DISTINCT FROM 'vercel.app' THEN
        RAISE EXCEPTION 'banner origin registrable domain mismatch';
    END IF;
END $$;

INSERT INTO cmp_domains (
    id,
    tenant_id,
    organization_id,
    domain,
    source_promotion_requested_at,
    created_at,
    updated_at
)
SELECT
    generate_gid(decode_base64_unpadded(grouped.tenant_id), 146),
    grouped.tenant_id,
    grouped.organization_id,
    grouped.domain,
    now(),
    now(),
    now()
FROM (
    SELECT DISTINCT ON (organization_id, domain)
        tenant_id,
        organization_id,
        domain
    FROM (
        SELECT
            tenant_id,
            organization_id,
            id,
            cmp_banner_registrable_domain(origin) AS domain
        FROM cookie_banners
        WHERE cmp_domain_id IS NULL
          AND NOT (capabilities @> '{"corsless": true}'::jsonb)
    ) parsed
    WHERE domain <> ''
    ORDER BY organization_id, domain, id
) grouped
ON CONFLICT (organization_id, domain) DO NOTHING;

WITH attached AS (
    UPDATE cookie_banners AS banner
    SET cmp_domain_id = domain.id
    FROM cmp_domains AS domain
    WHERE banner.cmp_domain_id IS NULL
      AND NOT (banner.capabilities @> '{"corsless": true}'::jsonb)
      AND domain.organization_id = banner.organization_id
      AND domain.domain = cmp_banner_registrable_domain(banner.origin)
    RETURNING banner.cmp_domain_id
)
UPDATE cmp_domains AS domain
SET source_promotion_requested_at = COALESCE(domain.source_promotion_requested_at, now())
WHERE domain.id IN (SELECT cmp_domain_id FROM attached)
  AND domain.source_promotion_requested_at IS NULL;


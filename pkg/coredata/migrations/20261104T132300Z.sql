-- Backfill cmp_domains for existing banners.
--
-- The domain is the label in front of the longest matching ICANN suffix.
-- A wildcard (kind 1, stored without "*.") matches one extra label, so ck
-- means *.ck. An exception (kind 2, stored without "!") wins over a wildcard,
-- so www.ck means !www.ck and its public suffix is ck. A host that matches
-- nothing uses its last label, which is why com and vercel.app have no row:
-- example.com stays example.com, and foo.vercel.app becomes vercel.app.
--
-- The rows are the ICANN section of publicsuffix.org git revision
-- d6c92f1bbb7433e5db7b8405c25d4035fb8ff376 (the list compiled into
-- golang.org/x/net v0.61.0), excluding plain single-label rules. Private
-- suffixes are omitted on purpose. Corsless banners are left unattached:
-- they accept reports from any origin, so their cookies are not evidence
-- about the banner origin.

CREATE TABLE cmp_domain_psl (
    suffix TEXT NOT NULL,
    kind SMALLINT NOT NULL,
    PRIMARY KEY (suffix, kind)
);

CREATE FUNCTION cmp_registrable_domain(raw_host text) RETURNS text
LANGUAGE plpgsql STABLE AS $$
DECLARE
    host text;
    labels text[];
    n int;
    i int;
    candidate text;
    rule_labels int;
    rule_normal boolean;
    rule_wildcard boolean;
    rule_exception boolean;
    best_len int := 0;
    best_suffix text := '';
    matched boolean := false;
    exc_len int := -1;
    exc_suffix text := '';
    public_suffix text;
    prefix text;
    last_label text;
    dot int;
    octet text;
    octets_ok boolean;
BEGIN
    host := lower(btrim(COALESCE(raw_host, '')));
    host := rtrim(host, '.');
    host := btrim(host, '[]');
    IF host = '' OR left(host, 1) = '.' OR position('..' IN host) > 0 THEN
        RETURN host;
    END IF;

    IF host ~ '^([0-9]{1,3}\.){3}[0-9]{1,3}$' THEN
        octets_ok := true;
        FOREACH octet IN ARRAY string_to_array(host, '.') LOOP
            IF octet::int > 255 THEN
                octets_ok := false;
            END IF;
        END LOOP;
        IF octets_ok THEN
            RETURN host;
        END IF;
    ELSIF position(':' IN host) > 0 THEN
        BEGIN
            PERFORM host::inet;
            RETURN host;
        EXCEPTION
            WHEN invalid_text_representation THEN
                NULL;
        END;
    END IF;

    labels := string_to_array(host, '.');
    n := cardinality(labels);

    FOR i IN 1..n LOOP
        candidate := array_to_string(labels[i:n], '.');
        rule_labels := n - i + 1;

        SELECT
            COALESCE(bool_or(kind = 0), false),
            COALESCE(bool_or(kind = 1), false),
            COALESCE(bool_or(kind = 2), false)
        INTO rule_normal, rule_wildcard, rule_exception
        FROM cmp_domain_psl
        WHERE suffix = candidate;

        IF rule_exception AND rule_labels > exc_len THEN
            exc_len := rule_labels;
            IF rule_labels = 1 THEN
                exc_suffix := '';
            ELSE
                exc_suffix := array_to_string(labels[i + 1:n], '.');
            END IF;
        END IF;

        IF rule_normal AND rule_labels > best_len THEN
            best_len := rule_labels;
            best_suffix := candidate;
            matched := true;
        END IF;

        IF i > 1 AND rule_wildcard AND (rule_labels + 1) > best_len THEN
            best_len := rule_labels + 1;
            best_suffix := labels[i - 1] || '.' || candidate;
            matched := true;
        END IF;
    END LOOP;

    IF exc_len >= 0 THEN
        public_suffix := exc_suffix;
    ELSIF NOT matched THEN
        public_suffix := labels[n];
    ELSE
        public_suffix := best_suffix;
    END IF;

    IF public_suffix = '' OR length(host) <= length(public_suffix) OR right(host, length(public_suffix) + 1) <> '.' || public_suffix THEN
        RETURN host;
    END IF;

    prefix := left(host, length(host) - length(public_suffix) - 1);
    dot := length(prefix) - length(regexp_replace(prefix, '^.*\.', ''));
    IF dot = 0 THEN
        last_label := prefix;
    ELSE
        last_label := right(prefix, length(prefix) - dot);
    END IF;

    RETURN last_label || '.' || public_suffix;
END;
$$;

CREATE FUNCTION cmp_banner_registrable_domain(raw_origin text) RETURNS text
LANGUAGE plpgsql STABLE AS $$
DECLARE
    raw text := btrim(COALESCE(raw_origin, ''));
    rest text;
    host text;
BEGIN
    IF raw = '' THEN
        RETURN '';
    END IF;

    IF raw ~ '^[a-zA-Z][a-zA-Z0-9+.-]*://' THEN
        rest := regexp_replace(raw, '^[a-zA-Z][a-zA-Z0-9+.-]*://', '');
        rest := split_part(rest, '/', 1);
        rest := split_part(rest, '?', 1);
        rest := split_part(rest, '#', 1);
        rest := regexp_replace(rest, '^[^@]*@', '');
        IF rest ~ '^\[[^\]]+\]' THEN
            host := substring(rest FROM '^\[([^\]]+)\]');
        ELSE
            host := regexp_replace(rest, ':[0-9]+$', '');
        END IF;
        host := lower(rtrim(host, '.'));
    ELSE
        host := lower(raw);
    END IF;

    RETURN cmp_registrable_domain(host);
END;
$$;


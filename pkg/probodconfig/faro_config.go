// FaroConfig is the browser telemetry sent by the console, employee portal,
// and compliance portal. The API key is visible to the page; it only
// authenticates the browser to the collector.
type FaroConfig struct {
	Enabled      bool   `json:"enabled"`
	APIKey       string `json:"api-key,omitempty"`
	CollectorURL string `json:"collector-url,omitempty"`
}

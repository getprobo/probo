package cloud

// Account is one account a cloud credential can reach: an AWS member
// account, an Azure subscription, a GCP project.
//
// ID is the identifier the cloud itself uses, and is the value a session is
// opened with — never a Probo identifier. Name is for display and may be
// empty; a cloud that has no name for an account is not an error.
type Account struct {
	ID   string
	Name string
}

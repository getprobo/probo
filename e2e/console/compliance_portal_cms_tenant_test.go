package console_test

import (
	"testing"

	"go.probo.inc/probo/e2e/internal/factory"
	"go.probo.inc/probo/e2e/internal/testutil"
)

func TestCompliancePortal_CMS_TenantIsolation(t *testing.T) {
	t.Parallel()

	org1Owner := testutil.NewClient(t, testutil.RoleOwner)
	org2Owner := testutil.NewClient(t, testutil.RoleOwner)

	org2PortalID := factory.CreateCompliancePortal(org2Owner)

	err := tryCreateCompliancePortalCMSReference(
		org1Owner,
		org2PortalID,
		factory.SafeName("Cross-tenant reference"),
		"https://example.com/cross",
	)
	testutil.RequireForbiddenError(
		t,
		err,
		"must not create references on another organization's portal",
	)
}
